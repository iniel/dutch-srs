"""nl-assemble: build book/tex/chapters-nl/hpmor-chapter-NNN.tex from the final scene files.

For every translatable block the English source is kept as `% EN:` comment lines
right before the Dutch paragraph (the hpmor-de convention), so later fixes can be
made against the original without opening the English chapter. Blocks without a
final translation are emitted in English with a `% TODO NL` marker so the chapter
still compiles while work is in progress.

    nl-assemble 1            # finals only (sNN.final.nl.md)
    nl-assemble 1 --draft    # fall back to the latest sNN.vK.nl.md where no final exists
    nl-assemble 1 --build    # also build book/pdf/hpmor-chapter-001-nl.pdf (xelatex or docker)
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

from .common import CHAPTERS_NL_DIR, DUTCH_DIR, PDF_DIR, REPO_DIR, chapter_work_dir, load_json, scene_dir
from .scenefile import latest_version, read_scene_file


def collect_translations(chapter: int, draft: bool) -> tuple[dict[str, str], dict[str, str]]:
    """-> (block id -> NL tex, scene id -> source description)."""
    cj = load_json(chapter_work_dir(chapter) / "chapter.json")
    sdir = scene_dir(chapter)
    nl: dict[str, str] = {}
    used: dict[str, str] = {}
    for s in cj["scenes"]:
        sid = s["scene"]
        final = sdir / f"{sid}.final.nl.md"
        path = None
        if final.exists():
            path = final
        elif draft:
            lv = latest_version(sdir, sid)
            path = lv[1] if lv else None
        if path is None:
            used[sid] = "missing"
            continue
        sf = read_scene_file(path)
        nl.update(sf.blocks)
        used[sid] = path.name
    return nl, used


_ONES = ["nul", "een", "twee", "drie", "vier", "vijf", "zes", "zeven", "acht", "negen", "tien", "elf", "twaalf", "dertien", "veertien", "vijftien", "zestien", "zeventien", "achttien", "negentien"]
_TENS = ["", "", "twintig", "dertig", "veertig", "vijftig", "zestig", "zeventig", "tachtig", "negentig"]


def dutch_number_word(n: int) -> str:
    """1 -> 'een', 21 -> 'eenentwintig', 122 -> 'honderdtweeëntwintig' (chapter headings)."""
    if n < 20:
        return _ONES[n]
    if n < 100:
        tens, ones = divmod(n, 10)
        if ones == 0:
            return _TENS[tens]
        link = "ën" if _ONES[ones][-1] == "e" else "en"
        return f"{_ONES[ones]}{link}{_TENS[tens]}"
    hundreds, rest = divmod(n, 100)
    head = "honderd" if hundreds == 1 else f"{_ONES[hundreds]}honderd"
    return head if rest == 0 else head + dutch_number_word(rest)


def render(chapter: int, nl: dict[str, str]) -> tuple[str, int, int]:
    cj = load_json(chapter_work_dir(chapter) / "chapter.json")
    out: list[str] = [
        f"% Generated by `nl-assemble {chapter}` from book/pipeline/work/ch{chapter:03d}/scenes/*.final.nl.md.",
        "% Do not edit by hand: fix the scene files and re-run. English source kept as `% EN:` lines.",
        f"\\renewcommand{{\\nlchapterword}}{{{dutch_number_word(chapter).upper()}}}",
        "",
    ]
    done = todo = 0
    first = True
    for b in cj["blocks"]:
        if not first and b["gap_before"]:
            out.append("")
        first = False
        if not b["translate"]:
            out.append(b["tex"])
            continue
        src_lines = b["tex"].splitlines()
        if b["id"] in nl and nl[b["id"]].strip():
            out.extend("% EN: " + ln if i == 0 else "% " + ln for i, ln in enumerate(src_lines))
            out.append(nl[b["id"]].strip())
            done += 1
        else:
            out.append(f"% TODO NL ({b['id']})")
            out.append(b["tex"])
            todo += 1
    return "\n".join(out).rstrip("\n") + "\n", done, todo


def _docker_image_exists(tag: str) -> bool:
    if not shutil.which("docker"):
        return False
    r = subprocess.run(["docker", "image", "inspect", tag], capture_output=True)
    return r.returncode == 0


def build_pdf(chapter: int) -> Path | None:
    """Single-chapter PDF via tools/build-chapter.sh (book/tex + the book/upstream layout and fonts).

    Uses a local xelatex when available, otherwise the `hpmor-tex` docker image
    (build it with: docker build -t hpmor-tex - < book/pipeline/Dockerfile.tex).
    """
    script = (DUTCH_DIR / "tools" / "build-chapter.sh").relative_to(REPO_DIR).as_posix()
    if shutil.which("xelatex"):
        cmd = ["sh", script, str(chapter)]
    elif _docker_image_exists("hpmor-tex"):
        cmd = ["docker", "run", "--rm", "--mount", f"type=bind,src={REPO_DIR},dst=/app", "hpmor-tex", "sh", script, str(chapter)]
        print(f"$ docker run … hpmor-tex {script} {chapter}", file=sys.stderr)
    else:
        print("xelatex not found and no hpmor-tex docker image; skipping PDF build (see book/pipeline/README.md)", file=sys.stderr)
        return None
    r = subprocess.run(cmd, cwd=REPO_DIR)
    target = PDF_DIR / f"hpmor-chapter-{chapter:03d}-nl.pdf"
    return target if r.returncode == 0 and target.exists() else None


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(prog="nl-assemble", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("chapter", type=int)
    ap.add_argument("--draft", action="store_true", help="use latest versions where no final exists")
    ap.add_argument("--build", action="store_true", help="build a single-chapter PDF with xelatex")
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args(argv)
    if not (chapter_work_dir(a.chapter) / "chapter.json").exists():
        raise SystemExit(f"chapter {a.chapter} not extracted; run nl-extract {a.chapter}")
    nl, used = collect_translations(a.chapter, a.draft)
    tex, done, todo = render(a.chapter, nl)
    out = a.out or (CHAPTERS_NL_DIR / f"hpmor-chapter-{a.chapter:03d}.tex")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(tex, encoding="utf-8")
    for sid, src in used.items():
        print(f"  {sid}: {src}")
    print(f"chapter {a.chapter}: {done} blocks translated, {todo} still English -> {out.relative_to(REPO_DIR)}")
    if a.build:
        pdf = build_pdf(a.chapter)
        if pdf:
            print(f"pdf -> {pdf.relative_to(REPO_DIR)}")


if __name__ == "__main__":
    main()
